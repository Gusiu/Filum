package pl.wspa.filum.crypto

import android.security.keystore.KeyGenParameterSpec
import android.os.Build
import android.security.keystore.KeyInfo
import android.security.keystore.KeyProperties
import android.security.keystore.StrongBoxUnavailableException
import android.util.Log
import java.math.BigInteger
import java.security.KeyFactory
import java.security.KeyPairGenerator
import java.security.KeyStore
import java.security.PrivateKey
import java.security.cert.X509Certificate
import java.security.spec.ECGenParameterSpec
import java.util.Calendar
import javax.net.ssl.KeyManager
import javax.security.auth.x500.X500Principal

/**
 * This phone's identity towards the server: a key pair in the Android Keystore and a
 * self-signed certificate the phone introduces itself with over mTLS (protocol §3.1,
 * ADR-005).
 *
 * The private key is created inside the Keystore and **never leaves it** - it cannot be
 * read even on a rooted phone, provided the device has StrongBox. The application only
 * ever holds a handle; the signing is done by the system.
 *
 * The certificate is generated by the Keystore itself when the key is created, so we need
 * neither BouncyCastle nor any other library for building X.509.
 */
/**
 * Gdzie fizycznie mieszka klucz prywatny.
 *
 * The distinction is practical, not merely descriptive. StrongBox is a separate chip
 * scalony odporny na atak fizyczny; TEE to wydzielony tryb tego samego procesora -
 * far better than nothing, but exposed to a class of attacks StrongBox is not.
 * Lower-end devices usually have only a TEE.
 */
enum class KeySecurity {
    /** Osobny element bezpieczny (Samsung Knox Vault i podobne). */
    STRONGBOX,

    /** The processor's trusted execution environment. */
    TRUSTED_ENVIRONMENT,

    /** The key in process memory - this should not happen on Android 11 or newer. */
    SOFTWARE,

    /** Could not be determined. */
    UNKNOWN;

    val isHardwareBacked: Boolean get() = this == STRONGBOX || this == TRUSTED_ENVIRONMENT
}

class DeviceIdentity private constructor(
    val alias: String,
    val certificate: X509Certificate,
    private val privateKey: PrivateKey,
    /** Where the private key lives. Shown to the user and recorded in the journal. */
    val security: KeySecurity,
) {

    /** The certificate in DER form - exactly what goes into the pairing request's `cert` field. */
    val certificateDer: ByteArray get() = certificate.encoded

    /** This device's public key fingerprint; the server knows it as `deviceKey`. */
    val pin: String by lazy { KeyPin.of(certificate) }

    /**
     * The key manager for mTLS.
     *
     * We deliberately do NOT use [javax.net.ssl.KeyManagerFactory]: the standard implementation
     * picks a certificate from the list of authorities the server expects. Our server sends no
     * such list (having no authority - ADR-005), so the default manager would pick nothing
     * and the handshake would proceed without a client certificate.
     */
    fun keyManagers(): Array<KeyManager> = arrayOf(FixedKeyManager(alias, certificate, privateKey))

    companion object {
        private const val TAG = "FilumIdentity"
        private const val KEYSTORE = "AndroidKeyStore"
        const val DEFAULT_ALIAS = "filum-device-key"

        /** The validity period is irrelevant under key pinning - see [KeyPin]. It just must not expire. */
        private const val VALIDITY_YEARS = 50

        fun exists(alias: String = DEFAULT_ALIAS): Boolean = keyStore().containsAlias(alias)

        /**
         * Loads the identity, or creates it on first pairing.
         *
         * The key survives application updates but not an uninstall - the phone then loses its
         * identity and has to be paired again. That is intended: uninstalling the application
         * is meant to revoke its access to the backup.
         */
        fun loadOrCreate(alias: String = DEFAULT_ALIAS): DeviceIdentity {
            val store = keyStore()
            if (!store.containsAlias(alias)) return generate(alias)

            val certificate = store.getCertificate(alias) as? X509Certificate
            val key = store.getKey(alias, null) as? PrivateKey

            if (certificate == null || key == null) {
                // The entry is incomplete - the Keystore can end up like this after a failed
                // aktualizacji systemu. Odtwarzamy od zera; skutkiem jest ponowne parowanie.
                Log.w(TAG, "Incomplete Keystore entry for $alias, regenerating")
                store.deleteEntry(alias)
                return generate(alias)
            }

            return DeviceIdentity(alias, certificate, key, securityOf(key))
        }

        fun delete(alias: String = DEFAULT_ALIAS) {
            val store = keyStore()
            if (store.containsAlias(alias)) store.deleteEntry(alias)
        }

        private fun generate(alias: String): DeviceIdentity {
            // StrongBox is a separate chip; some devices have it and many do not, and some
            // implementations refuse particular parameters. Its absence must not stop the
            // application from working.
            val strongBox = tryGenerate(alias, useStrongBox = true)
            if (strongBox) Log.i(TAG, "Device key in StrongBox")
            else {
                tryGenerate(alias, useStrongBox = false)
                Log.i(TAG, "Device key in the ordinary Keystore (no StrongBox)")
            }

            val store = keyStore()
            val key = store.getKey(alias, null) as PrivateKey

            return DeviceIdentity(
                alias = alias,
                certificate = store.getCertificate(alias) as X509Certificate,
                privateKey = key,
                // We ask the Keystore rather than remembering what generation returned.
                // This value is read on every start-up, not only the first, and only the
                // Keystore knows what it actually did with the key.
                security = securityOf(key),
            )
        }

        private fun tryGenerate(alias: String, useStrongBox: Boolean): Boolean = try {
            val generator = KeyPairGenerator.getInstance(KeyProperties.KEY_ALGORITHM_EC, KEYSTORE)
            generator.initialize(specFor(alias, useStrongBox))
            generator.generateKeyPair()
            true
        } catch (e: StrongBoxUnavailableException) {
            if (!useStrongBox) throw e
            false
        } catch (e: Exception) {
            if (!useStrongBox) throw e
            Log.w(TAG, "StrongBox refused to generate the key, retrying without it", e)
            false
        }

        private fun specFor(alias: String, useStrongBox: Boolean): KeyGenParameterSpec {
            val notBefore = Calendar.getInstance().apply { add(Calendar.DAY_OF_YEAR, -1) }
            val notAfter = Calendar.getInstance().apply { add(Calendar.YEAR, VALIDITY_YEARS) }

            return KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_SIGN)
                .setAlgorithmParameterSpec(ECGenParameterSpec("secp256r1"))
                // TLS 1.3 signs with ecdsa_secp256r1_sha256; the other digests are added
                // so we do not fall over on an older version negotiation.
                .setDigests(
                    KeyProperties.DIGEST_SHA256,
                    KeyProperties.DIGEST_SHA384,
                    KeyProperties.DIGEST_SHA512,
                )
                .setCertificateSubject(X500Principal("CN=Filum Android Client"))
                .setCertificateSerialNumber(BigInteger.valueOf(System.currentTimeMillis()))
                .setCertificateNotBefore(notBefore.time)
                .setCertificateNotAfter(notAfter.time)
                // Synchronizacja idzie w tle, w nocy, przy zablokowanym ekranie -
                // requiring user authentication would stop it at the first file.
                .setUserAuthenticationRequired(false)
                .setIsStrongBoxBacked(useStrongBox)
                .build()
        }

        /**
         * Reads from the Keystore where the key actually lives.
         *
         * Up to and including Android 11 all that can be established is whether the key is in
         * hardware - telling StrongBox from a TEE arrived only in Android 12. In that case we
         * return TRUSTED_ENVIRONMENT, because that is the guarantee we are sure of.
         */
        private fun securityOf(key: PrivateKey): KeySecurity = try {
            val info = KeyFactory.getInstance(key.algorithm, KEYSTORE)
                .getKeySpec(key, KeyInfo::class.java)

            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
                when (info.securityLevel) {
                    KeyProperties.SECURITY_LEVEL_STRONGBOX -> KeySecurity.STRONGBOX
                    KeyProperties.SECURITY_LEVEL_TRUSTED_ENVIRONMENT -> KeySecurity.TRUSTED_ENVIRONMENT
                    KeyProperties.SECURITY_LEVEL_SOFTWARE -> KeySecurity.SOFTWARE
                    else -> KeySecurity.UNKNOWN
                }
            } else {
                @Suppress("DEPRECATION")
                if (info.isInsideSecureHardware) KeySecurity.TRUSTED_ENVIRONMENT else KeySecurity.SOFTWARE
            }
        } catch (e: Exception) {
            Log.w(TAG, "Could not determine the key's security level", e)
            KeySecurity.UNKNOWN
        }

        private fun keyStore(): KeyStore = KeyStore.getInstance(KEYSTORE).apply { load(null) }
    }
}
